/// Central design radii. Change a value here to update the whole app.
class AppRadii {
  AppRadii._();

  /// Default radius for fields, buttons, chips, containers.
  static const double sm = 2;

  /// Card radius used by [AppCard] and themed cards.
  static const double card = 2;

  /// Dialog / panel radius.
  static const double dialog = 2;

  /// Bottom sheet top corners only.
  static const double bottomSheet = 20;

  /// Input fields.
  static const double input = 2;

  /// Buttons.
  static const double button = 2;
}
